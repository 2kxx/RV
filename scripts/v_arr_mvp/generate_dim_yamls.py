"""RewardVerse MVP — generate per-dimension yaml configs for the 17 EvalVerse
second-level dimensions (excluding visual_quality which already has a
dedicated config).

Each generated yaml:
  * inherits the same model / api / video-input / B3-pointwise scoring
    calibration block as ``rubric_pipeline/config/v_arr_mvp_t2v.yaml``
  * differs only in the ``task_description`` block — which is rewritten
    per-dimension to embed the EvalVerse Aspect>Main name, the dimension's
    sub-key list, and a short natural-language definition
  * adds a ``# Audio:`` paragraph when ``needs_audio`` is True so Gemini
    knows to consume the video's native audio track
  * uses the canonical "no prompt supplied" wording for the four
    intrinsic dimensions (consistency, progression, logic, visual_quality)

Usage:
    python scripts/v_arr_mvp/generate_dim_yamls.py
    python scripts/v_arr_mvp/generate_dim_yamls.py --dimension character
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

_THIS_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(_THIS_DIR))
from dimension_registry import (  # type: ignore  # noqa: E402
    DIMENSIONS,
    DIMENSIONS_BY_NAME,
    DimensionSpec,
)


# -----------------------------------------------------------------------------
# Static blocks shared by every per-dimension yaml.
# -----------------------------------------------------------------------------
SHARED_HEAD = """\
# AUTO-GENERATED by scripts/v_arr_mvp/generate_dim_yamls.py.
# Do NOT edit by hand. Re-run that script to regenerate.
#
# This config drives RewardVerse MVP rubric generation for ONE EvalVerse
# second-level dimension. The model / api / video / pointwise calibration
# blocks are inherited verbatim from rubric_pipeline/config/v_arr_mvp_t2v.yaml.
"""

SHARED_TAIL = """\
# Tencent Venus llmproxy (OpenAI-compatible).
base_url: "http://v2.open.venus.oa.com/llmproxy"
model_name: "gemini-3.1-pro"
api_key: "${OPENAI_API_KEY}"

# Auto-Rubric loop settings.
query_specific_generate_number: 5
enable_categorization: true
categories_number: 5
max_retries: 5
max_epochs: 5

video_input_strategy: "native_video"
"""


def _scoring_calibration_block() -> str:
    """Verbatim copy of the B3 (2026-05) pointwise calibration paragraph used
    in v_arr_mvp_t2v.yaml. Kept as a constant here so every dimension's
    pointwise grading uses the same independent-1-5 scale."""
    return """\

  ## Pointwise scoring calibration (B3, 2026-05)
  When this judge is used in POINTWISE mode (single-video absolute scoring on
  a 1-5 scale), every rubric must be scored INDEPENDENTLY:
    - Score 5 = excellent (this rubric is fully met; nearly flawless).
    - Score 4 = good (overall met; only minor blemishes).
    - Score 3 = acceptable (partially met; notable but non-fatal flaws).
    - Score 2 = poor (largely unmet; significant defects on this rubric).
    - Score 1 = unacceptable (this rubric is completely unmet or violated).
  HARD constraints, in priority order:
    1. A failure on rubric A must NOT drag down rubrics B/C/D. Each rubric is
       judged ONLY on the capability it describes.
    2. Do not default to 1 or 2 because of one localized flaw. Judge the
       rubric's overall behaviour FIRST, then weigh the severity. One minor
       blemish is roughly a 4; several notable blemishes are roughly a 3.
    3. Do NOT collapse to 2-3. Reserve 5 for genuinely excellent execution
       and 1 for genuine failures. Use the full 1-5 range.
    4. Do NOT compute the final aggregated score yourself. Just emit an
       integer verdict per rubric. The system aggregates them with equal
       weights afterwards.
"""


# -----------------------------------------------------------------------------
# Per-dimension task_description block.
# -----------------------------------------------------------------------------
def _task_description_block(dim: DimensionSpec) -> str:
    """Build the dimension-specific portion of the yaml task_description.

    The text starts with:
      * an EvalVerse Aspect>Main attribution line so the LLM knows the
        rubric should target ONE second-level dimension and not drift into
        adjacent ones
      * the natural-language definition (from registry.description_en)
      * the explicit list of sub-aspects this dimension covers (so the
        rubrics that emerge are tied to those concrete aspects)
      * a no-prompt clause for the 4 intrinsic dimensions, OR a
        prompt-aware clause for the rest
      * an audio clause for vocal/soundscape

    All of this lives INSIDE a single yaml ``task_description: |`` block.
    """
    sub_aspects = "\n".join(f"    - {k}" for k in dim.sub_keys)

    if dim.expose_prompt:
        prompt_clause = (
            "  When evaluating, the user instruction prompt IS available; "
            "factor in whether the video faithfully realises what the prompt "
            "asks for IN THIS DIMENSION (e.g. for 'character', whether each "
            "described persona is identifiable; for 'action', whether the "
            "described motion plays out plausibly), but do NOT score the "
            "prompt-fidelity of OTHER dimensions here."
        )
    else:
        prompt_clause = (
            "  This is an INTRINSIC dimension: judge it from the video "
            "alone, WITHOUT consulting any user prompt. Even if a prompt "
            "string is supplied, treat it as a placeholder and ignore its "
            "content. Rubrics must rely solely on visual / temporal "
            "evidence in the clip itself."
        )

    audio_clause = ""
    if dim.needs_audio:
        audio_clause = (
            "\n\n  ## Audio\n"
            "  This dimension REQUIRES the audio track. The video clips are "
            "submitted as native multimodal_url blocks which carry the audio "
            "track natively for the Gemini judge — no separate audio block "
            "is needed. Rubrics MUST cite audible evidence (e.g. presence/"
            "absence of dialogue, naturalness of vocal timbre, lip-sync "
            "alignment with mouth motion, synchronisation between sound "
            "effects and visual events, music-scene affective alignment), "
            "not just visual cues."
        )

    rubrics_clause = (
        "\n\n  ## Rubric requirements\n"
        "  Rubrics MUST be:\n"
        "    - Observable from the supplied video clip(s) alone\n"
        "    - Discriminative between the winner Vw (rank 1) and the loser "
        "Vl (rank 2)\n"
        "    - Written in plain natural language; NO benchmark-specific "
        "bracket prefixes\n"
        "    - Free of generic 'looks better' phrasing — be concrete\n"
        "    - Tied to the sub-aspects listed above; do NOT drift into "
        "neighbouring dimensions"
    )

    return f"""\
task_description: |
  This rubric judge evaluates ONE EvalVerse second-level dimension:
    {dim.aspect} > {dim.main}  (slug: {dim.name})

  {dim.description_en}

  Sub-aspects covered by this dimension (each rubric should ground itself
  in one or more of these):
{sub_aspects}

{prompt_clause}{audio_clause}{rubrics_clause}
"""


# -----------------------------------------------------------------------------
# Render one yaml.
# -----------------------------------------------------------------------------
def render_yaml(dim: DimensionSpec) -> str:
    grader_name = f"v-arr-mvp {dim.name} t2v judge"
    parts: list[str] = []
    parts.append(SHARED_HEAD)
    parts.append(f'grader_name: "{grader_name}"\n')
    parts.append('language: "en"\n')
    parts.append('task_type: "t2v"\n')
    # The yaml-level eval_mode is just a default; judger.py auto-detects
    # pairwise vs pointwise from the dataset's actual schema (see
    # _detect_eval_mode_from_dataset). We still set listwise as the default
    # because per-dimension v2_prompt_pair seeds are listwise.
    parts.append('eval_mode: "listwise"\n')
    parts.append('min_score: 1\n')
    parts.append('max_score: 5\n')
    parts.append('\n')
    parts.append(f'# Dimension metadata pinned by registry (do not edit by hand).\n')
    parts.append(f'dimension: "{dim.name}"\n')
    parts.append(f'evalverse_aspect: "{dim.aspect}"\n')
    parts.append(f'evalverse_main: "{dim.main}"\n')
    parts.append(f'expose_prompt: {str(dim.expose_prompt).lower()}\n')
    parts.append(f'needs_audio: {str(dim.needs_audio).lower()}\n')
    parts.append('\n')
    parts.append(_task_description_block(dim))
    parts.append(_scoring_calibration_block())
    parts.append('\n')
    parts.append(SHARED_TAIL)
    return "".join(parts)


# -----------------------------------------------------------------------------
# CLI.
# -----------------------------------------------------------------------------
def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--dimension", default=None,
        help="single dimension name (default: regenerate all 17 except "
             "visual_quality, which has its own canonical yaml)",
    )
    ap.add_argument(
        "--config_dir", default="rubric_pipeline/config",
        help="output directory for the per-dimension yaml files",
    )
    args = ap.parse_args()

    cfg_dir = Path(args.config_dir)
    cfg_dir.mkdir(parents=True, exist_ok=True)

    if args.dimension:
        dims = [DIMENSIONS_BY_NAME[args.dimension.lower().strip()]]
    else:
        # All EvalVerse 17 second-level dims except visual_quality (which
        # already lives in v_arr_mvp_t2v.yaml and serves as the RewardVerse MVP
        # baseline experiment).
        dims = [d for d in DIMENSIONS if d.name != "visual_quality"]

    print(f"writing {len(dims)} yaml files into {cfg_dir} ...")
    for d in dims:
        out_path = cfg_dir / f"v_arr_mvp_{d.name}_t2v.yaml"
        out_path.write_text(render_yaml(d), encoding="utf-8")
        print(f"  wrote -> {out_path}")
    print("done.")


if __name__ == "__main__":
    main()
