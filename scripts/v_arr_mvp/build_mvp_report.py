#!/usr/bin/env python3
"""Aggregate RewardVerse MVP diagnostics into a single Markdown report.

Reads (any subset) of:
  - rubric Auto-Rubric judge accuracy log (judger.py stdout / json)
  - zero_shot_judge.py output JSON
  - positional_bias.py output JSON
  - classify_rubric_categories.py output JSON

Emits:
  - A Markdown decision sheet covering RQ1..RQ4 with PASS / WARN / FAIL lights.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def _load_json(path: str | None) -> dict | None:
    if not path:
        return None
    p = Path(path)
    if not p.exists():
        return None
    return json.loads(p.read_text(encoding="utf-8"))


def _pct(value: float | None) -> str:
    if value is None:
        return "n/a"
    return f"{value:.2%}"


def _light(value: float | None, ok: float, warn: float) -> str:
    if value is None:
        return "?"
    if value >= ok:
        return "PASS"
    if value >= warn:
        return "WARN"
    return "FAIL"


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the RewardVerse MVP Markdown report.")
    parser.add_argument(
        "--rubric_judge_json",
        default=None,
        help="JSON dump from judger.evaluate (override via --rubric_judge_json).",
    )
    parser.add_argument("--zero_shot_json", default=None)
    parser.add_argument("--positional_bias_json", default=None)
    parser.add_argument("--rubric_categories_json", default=None)
    parser.add_argument("--rubric_judge_acc", type=float, default=None,
                        help="Optional manual override: rubric pairwise accuracy.")
    parser.add_argument("--zero_shot_acc", type=float, default=None,
                        help="Optional manual override.")
    parser.add_argument("--output", default="mvp_report.md")
    args = parser.parse_args()

    rubric_judge = _load_json(args.rubric_judge_json) or {}
    zero_shot = _load_json(args.zero_shot_json) or {}
    pos_bias = _load_json(args.positional_bias_json) or {}
    rubric_cats = _load_json(args.rubric_categories_json) or {}

    rubric_acc = (
        args.rubric_judge_acc
        if args.rubric_judge_acc is not None
        else rubric_judge.get("accuracy")
    )
    zero_acc = (
        args.zero_shot_acc
        if args.zero_shot_acc is not None
        else zero_shot.get("accuracy")
    )
    consistency = pos_bias.get("consistency_rate")
    temporal_frac = (rubric_cats.get("fractions") or {}).get("temporal")
    fractions = rubric_cats.get("fractions") or {}
    counts = rubric_cats.get("counts") or {}

    rq1_light = _light(rubric_acc, ok=0.70, warn=0.55)
    rq2_light = _light(temporal_frac, ok=0.30, warn=0.20)
    rq3_light = _light(consistency, ok=0.70, warn=0.50)

    # RQ4: rubric must beat zero-shot. Use delta; PASS if rubric > zero-shot by ≥5pp.
    if rubric_acc is not None and zero_acc is not None:
        delta = rubric_acc - zero_acc
        if delta >= 0.05:
            rq4_light = "PASS"
        elif delta >= 0.0:
            rq4_light = "WARN"
        else:
            rq4_light = "FAIL"
    else:
        delta = None
        rq4_light = "?"

    overall_lights = [rq1_light, rq2_light, rq3_light, rq4_light]
    pass_count = sum(1 for x in overall_lights if x == "PASS")
    overall_status = (
        "GREEN  (>=3 PASS, proceed to Paradigm C)"
        if pass_count >= 3
        else "YELLOW  (improve M5 prompt, retry verify-refine)"
        if pass_count >= 1
        else "RED  (fall back to RewardVerse-as-Evaluator only or Hybrid)"
    )

    md = []
    md.append("# RewardVerse MVP Decision Report\n")
    md.append("Generated by `scripts/v_arr_mvp/build_mvp_report.py`.\n")

    md.append("## Summary\n")
    md.append(
        "| RQ | Metric | Value | Status |\n"
        "|----|--------|-------|--------|\n"
        f"| RQ1: Auto-Rubric judge pairwise accuracy | `accuracy` | {_pct(rubric_acc)} | {rq1_light} |\n"
        f"| RQ2: Temporal rubric emergence | `fractions.temporal` | {_pct(temporal_frac)} | {rq2_light} |\n"
        f"| RQ3: Positional-swap consistency | `consistency_rate` | {_pct(consistency)} | {rq3_light} |\n"
        f"| RQ4: Rubric > Zero-shot baseline | `rubric_acc - zero_shot_acc` | {_pct(delta)} | {rq4_light} |\n",
    )
    md.append(f"\n**Overall: {overall_status}**\n")

    md.append("\n## Inputs\n")
    md.append(
        f"- rubric judger json: `{args.rubric_judge_json or 'n/a'}`\n"
        f"- zero-shot json: `{args.zero_shot_json or 'n/a'}`\n"
        f"- positional bias json: `{args.positional_bias_json or 'n/a'}`\n"
        f"- rubric categories json: `{args.rubric_categories_json or 'n/a'}`\n",
    )

    md.append("\n## RQ1 — Auto-Rubric judge accuracy\n")
    md.append(
        f"- total: {rubric_judge.get('total', 'n/a')}\n"
        f"- correct: {rubric_judge.get('correct', 'n/a')}\n"
        f"- accuracy: {_pct(rubric_acc)}\n",
    )

    md.append("\n## RQ2 — Rubric category distribution\n")
    if fractions:
        for cat in ("spatial", "temporal", "instruction", "quality", "unknown"):
            md.append(
                f"- **{cat}**: {counts.get(cat, 0)} ({_pct(fractions.get(cat))})\n",
            )
        md.append(
            f"- threshold: `temporal >= {rubric_cats.get('temporal_threshold', 0.30):.0%}` "
            f"-> {'PASS' if rubric_cats.get('temporal_threshold_passed') else 'FAIL'}\n",
        )
    else:
        md.append("- (no rubric categorization json provided)\n")

    md.append("\n## RQ3 — Positional swap consistency\n")
    md.append(
        f"- consistency rate: {_pct(consistency)}\n"
        f"- original-order accuracy: {_pct(pos_bias.get('orig_accuracy'))}\n"
        f"- flipped-order accuracy: {_pct(pos_bias.get('flip_accuracy'))}\n"
        f"- left-wins rate (0.5 = unbiased): {_pct(pos_bias.get('left_wins_rate'))}\n",
    )

    md.append("\n## RQ4 — Rubric judge vs zero-shot baseline\n")
    md.append(
        f"- rubric accuracy: {_pct(rubric_acc)}\n"
        f"- zero-shot accuracy: {_pct(zero_acc)}\n"
        f"- delta: {_pct(delta)}\n",
    )

    md.append("\n## Decision Tree\n")
    md.append("- **GREEN (>=3 PASS)**: proceed with Paradigm C; start RewardVerse Evaluator + supervision ablation.\n")
    md.append("- **YELLOW (1-2 PASS)**: harden M5 prompt for temporal coverage; raise max_epochs; consider motion/optical-flow grounding tools.\n")
    md.append("- **RED (0 PASS)**: fall back to RewardVerse-as-Evaluator only, or run Hybrid (B + partial A).\n")

    Path(args.output).write_text("".join(md), encoding="utf-8")
    print(f"Wrote {args.output}")
    print(f"Overall: {overall_status}")


if __name__ == "__main__":
    main()
