"""Refresh runs/v_arr_mvp_dim/_runall_summary.tsv and all_dims_summary.md
from per-dim pointwise.json files.

Usage:
    python scripts/v_arr_mvp/refresh_dim_summary.py

This is a pure file-IO aggregation; no model is called. It just walks
runs/v_arr_mvp_dim/<dim>/pointwise.json for every known RewardVerse L2 dim and
emits:
  - runs/v_arr_mvp_dim/_runall_summary.tsv  (tab-separated, one row per dim)
  - runs/v_arr_mvp_dim/all_dims_summary.md  (Markdown view of the same)
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIM_ROOT = ROOT / "runs" / "v_arr_mvp_dim"

# 17 RewardVerse L2 dims (visual_quality is the legacy one, intentionally omitted
# to match the existing all_dims_summary.md convention).
DIMS = (
    "character", "scene",
    "consistency", "action", "expression",
    "composition", "lens", "pacing",
    "chromaticity", "materiality", "lighting",
    "grounding", "progression",
    "logic", "rhythm",
    "vocal", "soundscape",
)


def _read_metrics(dim: str) -> dict | None:
    p = DIM_ROOT / dim / "pointwise.json"
    if not p.is_file():
        return None
    try:
        j = json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return None
    m = j.get("metrics") or {}
    return {
        "plcc":       m.get("plcc"),
        "srcc":       m.get("srcc"),
        "mae_zs":     m.get("mae_zs"),
        "mae_affine": m.get("mae_affine"),
        "mae_raw":    m.get("mae_raw"),
        "n":          m.get("n"),
        "dataset":    j.get("dataset"),
        "rubrics":    j.get("rubrics_file"),
        "failures":   j.get("failures"),
    }


def _fmt(x, ndigits=4):
    if x is None:
        return "n/a"
    try:
        return f"{float(x):.{ndigits}f}"
    except Exception:
        return "n/a"


def main() -> None:
    rows = []
    for dim in DIMS:
        m = _read_metrics(dim)
        if m is None:
            rows.append({"dim": dim, "status": "MISSING", **{k: None for k in
                ("plcc", "srcc", "mae_zs", "mae_affine", "n", "dataset",
                 "failures")}})
        else:
            rows.append({
                "dim": dim,
                "status": "OK",
                "plcc": m["plcc"],
                "srcc": m["srcc"],
                "mae_zs": m["mae_zs"],
                "mae_affine": m["mae_affine"],
                "n": m["n"],
                "dataset": m["dataset"],
                "failures": m["failures"],
            })

    # ---- TSV ----
    tsv_path = DIM_ROOT / "_runall_summary.tsv"
    tsv_lines = ["dim\tstatus\tplcc\tsrcc\tmae_zs\tmae_affine\tn\tfailures\tdataset"]
    for r in rows:
        tsv_lines.append(
            f"{r['dim']}\t{r['status']}\t{_fmt(r['plcc'])}\t{_fmt(r['srcc'])}\t"
            f"{_fmt(r['mae_zs'])}\t{_fmt(r['mae_affine'])}\t"
            f"{r['n'] if r['n'] is not None else 'n/a'}\t"
            f"{r['failures'] if r['failures'] is not None else 'n/a'}\t"
            f"{r['dataset'] or 'n/a'}"
        )
    tsv_path.write_text("\n".join(tsv_lines) + "\n", encoding="utf-8")

    # ---- Aggregate stats over OK rows ----
    ok = [r for r in rows if r["status"] == "OK" and r["plcc"] is not None]
    n_ok = len(ok)
    mean_plcc = sum(float(r["plcc"]) for r in ok) / n_ok if n_ok else None
    mean_srcc = sum(float(r["srcc"]) for r in ok if r["srcc"] is not None) / n_ok if n_ok else None
    mean_mae  = sum(float(r["mae_zs"]) for r in ok if r["mae_zs"] is not None) / n_ok if n_ok else None

    # ---- Markdown ----
    md_path = DIM_ROOT / "all_dims_summary.md"
    md = []
    md.append("# RewardVerse MVP — 17-dimension pointwise rubric metrics\n")
    md.append("Auto-generated by `scripts/v_arr_mvp/refresh_dim_summary.py`.\n")
    md.append("Each row reads `runs/v_arr_mvp_dim/<dim>/pointwise.json` "
              "produced by `scripts/v_arr_mvp/pointwise_rubric_judge.py`.\n")
    md.append("")
    md.append("| # | Dimension | Status | PLCC | SRCC | MAE_zs | MAE_affine | N | Failures |")
    md.append("|---|---|---|---:|---:|---:|---:|---:|---:|")
    for i, r in enumerate(rows, 1):
        md.append(
            f"| {i} | `{r['dim']}` | {r['status']} | "
            f"{_fmt(r['plcc'])} | {_fmt(r['srcc'])} | "
            f"{_fmt(r['mae_zs'])} | {_fmt(r['mae_affine'])} | "
            f"{r['n'] if r['n'] is not None else 'n/a'} | "
            f"{r['failures'] if r['failures'] is not None else 'n/a'} |"
        )
    md.append("")
    md.append(f"**Aggregate over {n_ok} OK dims**: "
              f"mean PLCC = {_fmt(mean_plcc)}, "
              f"mean SRCC = {_fmt(mean_srcc)}, "
              f"mean MAE_zs = {_fmt(mean_mae)}.\n")
    md.append("")
    md.append("Per-dim test set (column `dataset` from each `pointwise.json`):\n")
    md.append("")
    md.append("| Dimension | Test set |")
    md.append("|---|---|")
    for r in rows:
        md.append(f"| `{r['dim']}` | `{r['dataset'] or 'n/a'}` |")
    md.append("")
    md_path.write_text("\n".join(md) + "\n", encoding="utf-8")

    # ---- Console echo ----
    print(f"[refresh] wrote {tsv_path}")
    print(f"[refresh] wrote {md_path}")
    print()
    print(f"Aggregate over {n_ok}/{len(rows)} OK dims:")
    print(f"  mean PLCC   = {_fmt(mean_plcc)}")
    print(f"  mean SRCC   = {_fmt(mean_srcc)}")
    print(f"  mean MAE_zs = {_fmt(mean_mae)}")
    print()
    print("Per-dim PLCC / SRCC / MAE_zs / N:")
    for r in rows:
        print(f"  {r['dim']:<14} {r['status']:<8} "
              f"PLCC={_fmt(r['plcc'])}  SRCC={_fmt(r['srcc'])}  "
              f"MAE_zs={_fmt(r['mae_zs'])}  N={r['n']}")


if __name__ == "__main__":
    main()
