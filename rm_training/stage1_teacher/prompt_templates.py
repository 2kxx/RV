"""rm_training.stage1_teacher.prompt_templates
==========================================
Prompt scaffolds for the teacher and (light-weight) caption synthesis.

We deliberately keep this thin: in v1 we do **not** synthesise captions —
the v_arr_mvp pair files already carry rich ``query`` strings that
double as captions (often containing shot-by-shot descriptions). If
later you decide to attach an auxiliary visual caption generated by a
separate model, the helper signatures here give you a place to plug it
in without touching ``build_gold_rubric_dataset.py``.
"""

from __future__ import annotations


# Public surface kept tiny so callers don't have to chase imports.
__all__ = ["build_caption", "build_teacher_query"]


def build_caption(query: str, video_path: str | None = None) -> str:
    """Default no-op caption: return the query unchanged.

    Replace with a real captioner later (e.g. Gemini single-shot) without
    breaking any callers.
    """
    return query or ""


def build_teacher_query(query: str, caption: str | None = None) -> str:
    """Compose the teacher (Gemini) input from raw query + optional caption."""
    if not caption or caption.strip() == query.strip():
        return query
    return f"{query}\n\n[Auxiliary caption]: {caption}"
